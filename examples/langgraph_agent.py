"""LangChain / LangGraph Agent Integration Example for CUHK Blackboard.

Demonstrates how to bind CUHK Blackboard plugin tools to an Agent.
"""

import sys
from pathlib import Path
from typing import Any, Dict, List

# Ensure cuhk_blackboard is importable when running script directly
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from cuhk_blackboard.tools import (
    AGENT_TOOLS_DEFINITIONS,
    TOOL_FUNCTION_MAP,
)


def get_agent_tools() -> List[Dict[str, Any]]:
    """Return tools in standard OpenAI / Anthropic function calling format."""
    return AGENT_TOOLS_DEFINITIONS


def execute_agent_tool_call(tool_name: str, arguments: Dict[str, Any]) -> Dict[str, Any]:
    """Dispatcher for tool calls generated by an LLM agent."""
    if tool_name not in TOOL_FUNCTION_MAP:
        return {"error": f"Tool '{tool_name}' is not recognized."}
    handler = TOOL_FUNCTION_MAP[tool_name]
    try:
        return handler(**arguments)
    except Exception as e:
        return {"error": f"Failed executing tool '{tool_name}': {str(e)}"}


if __name__ == "__main__":
    print("Available tools for Agent:")
    for t in get_agent_tools():
        print(f" - {t['name']}: {t['description']}")
